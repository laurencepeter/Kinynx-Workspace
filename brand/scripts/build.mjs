// Generates every Kinynx logo and app-icon asset from src/geometry.mjs.
//
//   cd brand && npm install && npm run build
//
// Outputs (all committed):
//   brand/logo/*.svg                         logo, glyph, wordmark, lockups
//   brand/ios/AppIcon.appiconset/            1024 default + dark + tinted (Xcode 16+)
//   brand/android/res/                       adaptive + monochrome + legacy mipmaps
//   brand/android/play-store-512.png
//   apps/web/{icon.svg,favicon.ico,apple-touch-icon.png,icon-*.png,manifest.webmanifest}
//
// PNGs are rasterised with headless Chromium (Playwright) so the output matches
// what browsers render from the SVG sources.

import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { deflateSync, inflateSync } from 'node:zlib';
import { COLORS, GRID, TILE_RADIUS, STROKE, GLYPH, WORDMARK, lineD } from '../src/geometry.mjs';

const BRAND = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ROOT = resolve(BRAND, '..');
const WEB = join(ROOT, 'apps/web');

// ---------- SVG builders ----------

function glyph({ stem, arm, collab, transform = '' }) {
  const t = transform ? ` transform="${transform}"` : '';
  return (
    `<g fill="none" stroke-width="${STROKE}" stroke-linecap="round"${t}>` +
    `<path d="${lineD(GLYPH.stem)}" stroke="${stem}"/>` +
    `<path d="${lineD(GLYPH.arm)}" stroke="${arm}"/>` +
    `<path d="${lineD(GLYPH.collab)}" stroke="${collab}"/>` +
    `</g>`
  );
}

function svg(viewBox, inner, label) {
  const [, , w, h] = viewBox.split(' ');
  const a11y = label ? ` role="img" aria-label="${label}"` : ' aria-hidden="true"';
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" width="${w}" height="${h}"${a11y}>${inner}</svg>\n`;
}

const colourGlyph = glyph({ stem: COLORS.white, arm: COLORS.white, collab: COLORS.mint });
const tile = (rx) => `<rect width="${GRID}" height="${GRID}"${rx ? ` rx="${rx}"` : ''} fill="${COLORS.violet}"/>`;

const MARK = svg(`0 0 ${GRID} ${GRID}`, tile(TILE_RADIUS) + colourGlyph, 'Kinynx');
const MARK_SQUARE = svg(`0 0 ${GRID} ${GRID}`, tile(0) + colourGlyph, 'Kinynx');
// Maskable PWA: glyph scaled to 90% so it clears the 80% safe circle with margin.
const MARK_MASKABLE = svg(
  `0 0 ${GRID} ${GRID}`,
  tile(0) + glyph({ stem: COLORS.white, arm: COLORS.white, collab: COLORS.mint, transform: 'translate(3.2 3.2) scale(0.9)' }),
  'Kinynx',
);
// Android legacy launcher: 48dp canvas with 2dp padding (keyline), rounded tile.
const MARK_LEGACY = svg(
  '0 0 48 48',
  `<g transform="translate(2 2) scale(${44 / GRID})">${tile(TILE_RADIUS)}${colourGlyph}</g>`,
  'Kinynx',
);
const MARK_LEGACY_ROUND = svg(
  '0 0 48 48',
  `<circle cx="24" cy="24" r="22" fill="${COLORS.violet}"/>` +
    `<g transform="translate(2 2) scale(${44 / GRID})">${colourGlyph}</g>`,
  'Kinynx',
);
const IOS_DARK = svg(`0 0 ${GRID} ${GRID}`, glyph({ stem: COLORS.violetLight, arm: COLORS.violetLight, collab: COLORS.mint }));
const IOS_TINTED = svg(`0 0 ${GRID} ${GRID}`, glyph({ stem: '#FFFFFF', arm: '#FFFFFF', collab: '#B8B8B8' }));

// Wordmark sized at 0.64x the mark height, optically centred on the joint.
const WM_SCALE = (GRID * 0.64) / WORDMARK.upm;
const GAP = GRID * 0.2;
const [wx0, wy0, wx1] = WORDMARK.bounds;
const wmX = GRID + GAP - wx0 * WM_SCALE;
const wmY = GRID / 2 - (wy0 / 2) * WM_SCALE;
const LOCKUP_W = Math.ceil(wmX + wx1 * WM_SCALE);
const wordmarkPath = (fill) =>
  `<path transform="translate(${wmX.toFixed(2)} ${wmY.toFixed(2)}) scale(${WM_SCALE})" fill="${fill}" d="${WORDMARK.d}"/>`;

function lockup({ tiled, glyphColours, text }) {
  const markInner = tiled ? tile(TILE_RADIUS) + colourGlyph : glyph(glyphColours);
  return svg(`0 0 ${LOCKUP_W} ${GRID}`, markInner + wordmarkPath(text), 'Kinynx');
}

const WORDMARK_SVG = (() => {
  const w = Math.ceil((wx1 - wx0) * WM_SCALE);
  const h = Math.ceil((WORDMARK.bounds[3] - wy0) * WM_SCALE);
  return svg(
    `0 0 ${w} ${h}`,
    `<path transform="scale(${WM_SCALE}) translate(${-wx0} ${-wy0})" fill="currentColor" d="${WORDMARK.d}"/>`,
    'Kinynx',
  );
})();

// ---------- Android vector drawables (108dp adaptive canvas, glyph centred) ----------

function vectorDrawable(colours) {
  const off = (108 - GRID) / 2; // 22dp: centres the 64u grid in the 108dp canvas
  const path = (d, c) =>
    `    <path\n        android:pathData="${lineD(d, off, ',')}"\n        android:strokeColor="${c}"\n        android:strokeWidth="${STROKE}"\n        android:strokeLineCap="round" />`;
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by brand/scripts/build.mjs — do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
${path(GLYPH.stem, colours.stem)}
${path(GLYPH.arm, colours.arm)}
${path(GLYPH.collab, colours.collab)}
</vector>
`;
}

const ADAPTIVE = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by brand/scripts/build.mjs — do not edit by hand. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
`;

// ---------- Raster helpers ----------

let browser;
async function renderPng(svgText, size, { opaque = false } = {}) {
  if (!browser) {
    const { chromium } = await import('playwright');
    browser = await chromium.launch();
  }
  const page = await browser.newPage({ viewport: { width: size, height: size }, deviceScaleFactor: 1 });
  const sized = svgText.replace(/width="[^"]+" height="[^"]+"/, `width="${size}" height="${size}"`);
  await page.setContent(
    `<!doctype html><html><body style="margin:0;background:transparent">${sized}</body></html>`,
  );
  const png = await page.screenshot({ omitBackground: !opaque, clip: { x: 0, y: 0, width: size, height: size } });
  await page.close();
  return opaque ? stripAlpha(png) : png;
}

// App Store and apple-touch icons must not carry an alpha channel. Re-encode an
// RGBA PNG (8-bit, non-interlaced, as Chromium emits) as RGB.
function stripAlpha(png) {
  const ihdr = png.subarray(8 + 8, 8 + 8 + 13);
  const width = ihdr.readUInt32BE(0);
  const height = ihdr.readUInt32BE(4);
  const bitDepth = ihdr[8];
  const colourType = ihdr[9];
  if (colourType === 2) return png; // already RGB
  if (colourType !== 6 || bitDepth !== 8 || ihdr[12] !== 0) throw new Error('unexpected PNG format');

  const idat = [];
  for (let off = 8; off < png.length; ) {
    const len = png.readUInt32BE(off);
    const type = png.toString('ascii', off + 4, off + 8);
    if (type === 'IDAT') idat.push(png.subarray(off + 8, off + 8 + len));
    off += 12 + len;
  }
  const raw = inflateSync(Buffer.concat(idat));
  const bpp = 4;
  const stride = width * bpp;
  const rgba = Buffer.alloc(height * stride);
  // Undo PNG row filters.
  for (let y = 0; y < height; y++) {
    const filter = raw[y * (stride + 1)];
    const src = raw.subarray(y * (stride + 1) + 1, (y + 1) * (stride + 1));
    const out = rgba.subarray(y * stride, (y + 1) * stride);
    const prev = y > 0 ? rgba.subarray((y - 1) * stride, y * stride) : null;
    for (let i = 0; i < stride; i++) {
      const a = i >= bpp ? out[i - bpp] : 0;
      const b = prev ? prev[i] : 0;
      const c = prev && i >= bpp ? prev[i - bpp] : 0;
      let v = src[i];
      if (filter === 1) v += a;
      else if (filter === 2) v += b;
      else if (filter === 3) v += (a + b) >> 1;
      else if (filter === 4) {
        const p = a + b - c;
        const pa = Math.abs(p - a), pb = Math.abs(p - b), pc = Math.abs(p - c);
        v += pa <= pb && pa <= pc ? a : pb <= pc ? b : c;
      }
      out[i] = v & 0xff;
    }
  }
  const rgb = Buffer.alloc(height * (width * 3 + 1));
  for (let y = 0; y < height; y++) {
    rgb[y * (width * 3 + 1)] = 0;
    for (let x = 0; x < width; x++) {
      rgba.copy(rgb, y * (width * 3 + 1) + 1 + x * 3, y * stride + x * 4, y * stride + x * 4 + 3);
    }
  }
  const newIhdr = Buffer.from(ihdr);
  newIhdr[9] = 2;
  return Buffer.concat([png.subarray(0, 8), chunk('IHDR', newIhdr), chunk('IDAT', deflateSync(rgb, { level: 9 })), chunk('IEND', Buffer.alloc(0))]);
}

const CRC_TABLE = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(buf) {
  let c = 0xffffffff;
  for (const b of buf) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(td));
  return Buffer.concat([len, td, crc]);
}

// ICO with embedded PNG entries (supported by every current browser and Windows Vista+).
function ico(pngs) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(pngs.length, 4);
  const entries = [];
  let offset = 6 + 16 * pngs.length;
  for (const { size, data } of pngs) {
    const e = Buffer.alloc(16);
    e[0] = size >= 256 ? 0 : size;
    e[1] = size >= 256 ? 0 : size;
    e.writeUInt16LE(1, 4); // planes
    e.writeUInt16LE(32, 6); // bpp
    e.writeUInt32LE(data.length, 8);
    e.writeUInt32LE(offset, 12);
    offset += data.length;
    entries.push(e);
  }
  return Buffer.concat([header, ...entries, ...pngs.map((p) => p.data)]);
}

async function out(path, data) {
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, data);
  console.log('  ' + path.slice(ROOT.length + 1));
}

// ---------- Build ----------

async function main() {
  console.log('logo');
  await out(join(BRAND, 'logo/kinynx-mark.svg'), MARK);
  await out(join(BRAND, 'logo/kinynx-glyph.svg'), svg(`0 0 ${GRID} ${GRID}`, colourGlyph, 'Kinynx'));
  await out(
    join(BRAND, 'logo/kinynx-glyph-mono.svg'),
    svg(`0 0 ${GRID} ${GRID}`, glyph({ stem: 'currentColor', arm: 'currentColor', collab: 'currentColor' }), 'Kinynx'),
  );
  await out(join(BRAND, 'logo/kinynx-wordmark.svg'), WORDMARK_SVG);
  await out(join(BRAND, 'logo/kinynx-lockup-on-dark.svg'), lockup({ tiled: true, text: COLORS.text }));
  await out(join(BRAND, 'logo/kinynx-lockup-on-light.svg'), lockup({ tiled: true, text: COLORS.ink }));
  const black = { stem: '#000000', arm: '#000000', collab: '#000000' };
  const white = { stem: '#FFFFFF', arm: '#FFFFFF', collab: '#FFFFFF' };
  await out(join(BRAND, 'logo/kinynx-lockup-mono-black.svg'), lockup({ tiled: false, glyphColours: black, text: '#000000' }));
  await out(join(BRAND, 'logo/kinynx-lockup-mono-white.svg'), lockup({ tiled: false, glyphColours: white, text: '#FFFFFF' }));

  console.log('web');
  await out(join(WEB, 'icon.svg'), MARK);
  await out(
    join(WEB, 'favicon.ico'),
    ico(await Promise.all([16, 32, 48].map(async (size) => ({ size, data: await renderPng(MARK, size) })))),
  );
  await out(join(WEB, 'apple-touch-icon.png'), await renderPng(MARK_SQUARE, 180, { opaque: true }));
  await out(join(WEB, 'icon-192.png'), await renderPng(MARK, 192));
  await out(join(WEB, 'icon-512.png'), await renderPng(MARK, 512));
  await out(join(WEB, 'icon-maskable-512.png'), await renderPng(MARK_MASKABLE, 512, { opaque: true }));
  await out(
    join(WEB, 'manifest.webmanifest'),
    JSON.stringify(
      {
        name: 'Kinynx',
        short_name: 'Kinynx',
        start_url: '/',
        scope: '/',
        display: 'standalone',
        background_color: COLORS.ink,
        theme_color: COLORS.ink,
        icons: [
          { src: '/icon-192.png', sizes: '192x192', type: 'image/png' },
          { src: '/icon-512.png', sizes: '512x512', type: 'image/png' },
          { src: '/icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
          { src: '/icon.svg', sizes: 'any', type: 'image/svg+xml' },
        ],
      },
      null,
      2,
    ) + '\n',
  );

  console.log('ios');
  const IOS = join(BRAND, 'ios/AppIcon.appiconset');
  await out(join(IOS, 'AppIcon-1024.png'), await renderPng(MARK_SQUARE, 1024, { opaque: true }));
  await out(join(IOS, 'AppIcon-1024-dark.png'), await renderPng(IOS_DARK, 1024));
  await out(join(IOS, 'AppIcon-1024-tinted.png'), await renderPng(IOS_TINTED, 1024));
  await out(
    join(IOS, 'Contents.json'),
    JSON.stringify(
      {
        images: [
          { filename: 'AppIcon-1024.png', idiom: 'universal', platform: 'ios', size: '1024x1024' },
          {
            appearances: [{ appearance: 'luminosity', value: 'dark' }],
            filename: 'AppIcon-1024-dark.png',
            idiom: 'universal',
            platform: 'ios',
            size: '1024x1024',
          },
          {
            appearances: [{ appearance: 'luminosity', value: 'tinted' }],
            filename: 'AppIcon-1024-tinted.png',
            idiom: 'universal',
            platform: 'ios',
            size: '1024x1024',
          },
        ],
        info: { author: 'xcode', version: 1 },
      },
      null,
      2,
    ) + '\n',
  );

  console.log('android');
  const RES = join(BRAND, 'android/res');
  await out(join(RES, 'mipmap-anydpi-v26/ic_launcher.xml'), ADAPTIVE);
  await out(join(RES, 'mipmap-anydpi-v26/ic_launcher_round.xml'), ADAPTIVE);
  await out(
    join(RES, 'drawable/ic_launcher_foreground.xml'),
    vectorDrawable({ stem: COLORS.white, arm: COLORS.white, collab: COLORS.mint }),
  );
  await out(
    join(RES, 'drawable/ic_launcher_monochrome.xml'),
    vectorDrawable({ stem: '#FFFFFFFF', arm: '#FFFFFFFF', collab: '#FFFFFFFF' }),
  );
  await out(
    join(RES, 'values/ic_launcher_background.xml'),
    `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by brand/scripts/build.mjs — do not edit by hand. -->\n<resources>\n    <color name="ic_launcher_background">${COLORS.violet}</color>\n</resources>\n`,
  );
  const densities = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
  for (const [d, size] of Object.entries(densities)) {
    await out(join(RES, `mipmap-${d}/ic_launcher.png`), await renderPng(MARK_LEGACY, size));
    await out(join(RES, `mipmap-${d}/ic_launcher_round.png`), await renderPng(MARK_LEGACY_ROUND, size));
  }
  await out(join(BRAND, 'android/play-store-512.png'), await renderPng(MARK_SQUARE, 512, { opaque: true }));

}

// Headless Chromium can stall on close in sandboxed CI containers; don't let it hang the build.
const closeBrowser = () =>
  Promise.race([browser?.close(), new Promise((r) => setTimeout(r, 2000).unref())]);

main().then(async () => {
  await closeBrowser();
  process.exit(0);
}, async (err) => {
  await closeBrowser();
  if (err?.code === 'ERR_MODULE_NOT_FOUND') {
    console.error('Playwright is missing. Run `npm install` inside brand/ first.');
  } else {
    console.error(err);
  }
  process.exit(1);
});
